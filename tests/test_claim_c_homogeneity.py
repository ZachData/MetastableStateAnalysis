class TestCurveIsInStepWithTheGate:

    def test_committed_curve_is_not_stale(self):
        problems = check_curve(CURVE_PATH)
        assert problems == [], (
            "the committed curve no longer describes the current gate; "
            "regenerate with tools/calibrate_claim_c_homogeneity.py --write")

    def test_curve_records_what_it_measured(self):
        c = load_homogeneity_curve()
        assert c["schema_version"] == HOMOGENEITY_CURVE_SCHEMA_VERSION
        assert c["metrics"] == list(CLAIM_C_METRICS)
        assert c["alternative"] == CLAIM_C_ALTERNATIVE
        assert c["reciprocal_alternative"] == CLAIM_C_RECIPROCAL_ALTERNATIVE
        assert c["subset_names"] == [n for n, _ in SUBSETS]
        # The two things a reader must not have to infer: which H0 family the
        # rates are rates under, and that they are conditional on emission.
        assert "per-metric shared sign propensity" in c["_h0_family"]
        assert "conditional on the gate EMITTING" in c["_conditioning"]
        assert c["assumes_complete_table"] is True

    def test_quantile_rows_are_monotone_in_level(self):
        c = load_homogeneity_curve()
        for row in c["curves"].values():
            for b in row["bins"]:
                for key in ("quantiles_greater", "quantiles_less"):
                    q = b[key]
                    if q is None:
                        continue
                    assert list(q) == sorted(q), (
                        f"{key} is not a quantile function in bin {b['lo']}")

    def test_the_degenerate_top_bin_has_no_measurement(self):
        """
        Under H0 at homogeneity above 0.975 essentially every draw hits the
        identical-rows refusal, so there is no emitted distribution to
        calibrate against. The curve says so rather than extrapolating, and the
        gate refuses there.
        """
        c = load_homogeneity_curve()
        top = c["curves"]["8"]["bins"][-1]
        assert top["quantiles_greater"] is None
        assert not top["measured"]


