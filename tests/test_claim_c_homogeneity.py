"""
tests/test_claim_c_homogeneity.py — CLAIM-C's homogeneity calibration curve.

`POPPER_PLAN.md` §6f measured the two ends of CLAIM-C's one real limitation --
the prompts are not independent observations -- and left everything between
them uncontrolled. A real run lands in the middle. §6g closes that by measuring
the whole curve offline and having the gate report what its p corresponds to at
the homogeneity it observed.

Three things have to be true for that to be an improvement rather than a second
number to argue about, and this module is organised around them.

**The simulator must be the same test as the gate.** The curve is generated by
a second implementation of the gate's arithmetic -- a fast one, because the
honest version needs hundreds of thousands of draws. A second implementation is
a real risk, so `TestFastPathMatchesTheGate` pins it against `p_value_claim_c`
itself. If those two ever disagree, every number in the stored curve is a rate
of some other test and the correction is worse than nothing.

**The correction must actually restore calibration, and not only on the family
it was fitted to.** `TestCalibrationIsRestored` measures both. The
out-of-sample arm is the one that matters: `sign_homogeneity` is a scalar
summary, and a scalar cannot determine a distribution, so the question is
whether indexing by it transfers to a dependence mechanism the curve never saw.

**It must never buy power.** The exhaustive enumeration is genuinely
conservative at the independent end. `TestTheCorrectionNeverSharpens` pins that
the correction can only blunt.
"""

