# ---------------------------------------------------------------------------
# Fixtures: arms whose per-cell contrast SIGNS are exactly what we ask for
# ---------------------------------------------------------------------------

def _prompts(n):
    return [f"prompt_{i}" for i in range(n)]


def _arm(deltas, prompts, n_layers):
    return {p: {m: [float(deltas[i, j])] * n_layers
                for j, m in enumerate(CLAIM_C_METRICS)}
            for i, p in enumerate(prompts)}


def _four_arms(ref_signs, can_signs, prompts):
    n_p = len(prompts)
    zeros_ref = _arm(np.zeros((n_p, M)), prompts, REF_LAYERS)
    zeros_can = _arm(np.zeros((n_p, M)), prompts, CAN_LAYERS)
    return (_arm(ref_signs, prompts, REF_LAYERS), zeros_ref,
            _arm(can_signs, prompts, CAN_LAYERS), zeros_can)


def _step0(prompts):
    return _arm(np.full((len(prompts), M), 0.25), prompts, CAN_LAYERS)


def _gate(ref_signs, can_signs, prompts):
    rt, rr, ct, cr = _four_arms(ref_signs, can_signs, prompts)
    return p_value_claim_c(rt, rr, ct, cr, candidate_step0=_step0(prompts))


def _heterogeneous(n, seed=11):
    rng = np.random.default_rng(seed)
    while True:
        s = rng.choice([-1.0, 1.0], size=(n, M))
        if len({tuple(r) for r in s.tolist()}) > 1:
            return s


def _consistent_but_not_degenerate(n=8):
    """
    A candidate table with high `sign_homogeneity` and no degenerate subset.

    Every metric column has a single dissenting prompt, and a DIFFERENT one
    each time, so each column is 7/8 unanimous (homogeneity 0.875) while no two
    prompts carry the same sign row and no leave-one-out subset collapses. That
    separation matters: it is the only way to exercise the homogeneity refusal
    without simultaneously tripping the identical-rows one.
    """
    s = np.ones((n, M))
    for j in range(M):
        s[j % n, j] = -1.0
    return s


