class TestTheRecordSaysWhatWasCorrected:

    def test_the_note_carries_both_p_values_and_the_bin(self, tmp_path):
        prompts = _prompts(8)
        ref = _heterogeneous(8)
        rt, rr, ct, cr = _four_arms(ref, ref.copy(), prompts)
        res = adjudicate_claim_c(rt, rr, ct, cr, candidate_step0=_step0(prompts),
                                 adjudicate=True, adjudications_dir=tmp_path)
        assert res["adjudication"] is not None
        rec = json.loads((tmp_path / "CLAIM-C.json").read_text())
        notes = rec["notes"]
        assert "homogeneity_correction" in notes
        assert "p_uncorrected" in notes
        # The adjudicated number is the corrected one.
        assert rec["p_value"] == pytest.approx(res["p_value"])

    def test_the_ledger_is_untouched_without_the_flag(self, tmp_path):
        prompts = _prompts(8)
        ref = _heterogeneous(8)
        rt, rr, ct, cr = _four_arms(ref, ref.copy(), prompts)
        res = adjudicate_claim_c(rt, rr, ct, cr, candidate_step0=_step0(prompts),
                                 adjudications_dir=tmp_path)
        assert res["adjudication"] is None
        assert not list(tmp_path.iterdir())
