class TestTheDerivedRefusal:
    """
    The second question this construction had to settle was whether there is a
    homogeneity above which the gate refuses instead of correcting. There is,
    and it is derived from alpha exactly as the attainable-floor refusal is:
    refuse where the measured rate at the design's BEST attainable p already
    exceeds alpha, because then no result whatsoever survives its own
    correction. No homogeneity constant appears anywhere in the module.
    """

    def test_high_homogeneity_refuses_rather_than_reporting_a_corrected_p(self):
        prompts = _prompts(8)
        can = _consistent_but_not_degenerate(8)
        r = _gate(can.copy(), can, prompts)
        assert r["sign_homogeneity"] == pytest.approx(0.875)
        assert r["p_value"] is None
        assert "would not survive its own correction" in r["reason"]
        assert r["verdict"] == "INSUFFICIENT"
        # Refusing is not falsifying: nothing was shown either way.
        assert r["falsified"] is False
        assert r["hard_stop"] is True

    def test_the_boundary_moves_with_alpha_because_it_is_derived_from_it(self, monkeypatch):
        """
        The distinguishing property of a derived cut over a placed one. A
        tolerance would sit at the same homogeneity whatever alpha is.
        """
        import p1_mstate_tracking.replication_gate as gate
        prompts = _prompts(8)
        can = _consistent_but_not_degenerate(8)

        monkeypatch.setattr(gate, "_alpha", lambda: 0.5)
        r = _gate(can.copy(), can, prompts)
        assert r["alpha"] == 0.5
        assert r["p_value"] is not None, (
            "the refusal did not move when alpha did, so it is a placed "
            "threshold rather than a derived one")

    def test_the_refusal_reports_what_it_measured(self):
        prompts = _prompts(8)
        r = _gate(_consistent_but_not_degenerate(8).copy(),
                  _consistent_but_not_degenerate(8), prompts)
        hc = r["homogeneity_correction"]
        assert hc["available"] is True
        assert hc["bin_lo"] <= r["sign_homogeneity"] <= hc["bin_hi"]
        assert hc["corrected_best_attainable_p"] > r["alpha"]
        # The quantile rows themselves stay out of the result: they are 55
        # numbers per direction and the record should say which bin was read,
        # not reproduce the table.
        assert "quantiles_greater" not in hc


class TestRefusesRatherThanFallingBackToTheUncorrectedP:
    """
    Once the correction is what enters the e-value, an uncorrected p reaching
    the ledger is not a degraded answer -- it is a Type-I guarantee asserted on
    a null already measured to be anticonservative. So every way of failing to
    get a correction is a refusal.
    """

    def _unreadable(self, tmp_path, payload=None):
        p = tmp_path / "curve.json"
        if payload is not None:
            p.write_text(json.dumps(payload))
        return p

    def test_a_missing_curve_refuses(self, tmp_path):
        corr = homogeneity_correction(8, 0.6, 0, 8 * M,
                                      path=tmp_path / "absent.json")
        assert corr["available"] is False
        assert "could not be read" in corr["reason"]

    def test_a_curve_at_another_schema_version_refuses(self, tmp_path):
        p = self._unreadable(tmp_path, {"schema_version": 999})
        corr = homogeneity_correction(8, 0.6, 0, 8 * M, path=p)
        assert corr["available"] is False
        assert "schema_version" in corr["reason"]

    def test_a_curve_measured_on_other_metrics_refuses(self, tmp_path):
        p = self._unreadable(tmp_path, {
            "schema_version": HOMOGENEITY_CURVE_SCHEMA_VERSION,
            "metrics": ["only_one_metric"]})
        corr = homogeneity_correction(8, 0.6, 0, 8 * M, path=p)
        assert corr["available"] is False
        assert "different metric set" in corr["reason"]

    def test_an_untabulated_prompt_count_refuses(self):
        corr = homogeneity_correction(40, 0.6, 0, 40 * M)
        assert corr["available"] is False
        assert "no calibration curve is tabulated" in corr["reason"]

    def test_the_gate_refuses_and_does_not_quietly_report_the_exact_p(self, tmp_path):
        import p1_mstate_tracking.replication_gate as gate
        prompts = _prompts(8)
        ref = _heterogeneous(8)
        monkey = tmp_path / "absent.json"
        old = gate.HOMOGENEITY_CURVE_PATH
        try:
            gate.HOMOGENEITY_CURVE_PATH = monkey
            r = _gate(ref, ref.copy(), prompts)
        finally:
            gate.HOMOGENEITY_CURVE_PATH = old
        assert r["p_value"] is None
        assert "the correction is what enters the e-value" in r["reason"]
        assert r["hard_stop"] is True


