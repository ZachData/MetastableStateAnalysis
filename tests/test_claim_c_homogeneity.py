def _score(tables, table):
    """
    (homogeneity, emitted, p_greater) for a batch of COMPLETE concordance
    tables.

    `emitted` folds in the informative-row floor as well as the identical-rows
    degeneracy: a prompt whose six metrics split three and three cannot move
    the statistic, and a table with fewer than five that can is refused rather
    than reported. Leaving it out would measure the corrected rate over draws
    the gate never emits on, which is the conditioning error POPPER_PLAN.md 6g
    and 6k both turn on.
    """
    n_prompts = table.shape[1]
    f = table.mean(axis=1)
    hom = np.maximum(f, 1.0 - f).mean(axis=1)
    refused = np.zeros(len(table), dtype=bool)
    pg = np.zeros(len(table))
    floor = np.zeros(len(table))
    for _, cols in SUBSETS:
        sub = table[:, :, list(cols)]
        refused |= (sub == sub[:, :1, :]).all(axis=(1, 2))
        valid = np.full(sub.shape[:2], sub.shape[2], dtype=np.int64)
        conc = sub.sum(axis=2).astype(np.int64)
        k = (np.abs(valid - 2 * conc) > 0).sum(axis=1)
        floor = np.maximum(floor,
                           (2.0 ** (n_prompts - k) + 1.0) / (2 ** n_prompts + 1.0))
        pg = np.maximum(pg, tables[len(cols)].lookup(valid, conc)[0])
    refused |= floor > ALPHA
    return hom, ~refused, pg


def _corrected_rate(n_prompts, hom, emitted, pg, alpha=ALPHA):
    """The corrected gate's rejection rate among the draws it emits on."""
    floor = best_attainable_p(n_prompts)
    n_em = n_rej = 0
    for h, p, e in zip(hom, pg, emitted):
        if not e:
            continue
        corr = homogeneity_correction(n_prompts, float(h), 0, n_prompts * M)
        if not corr["available"]:
            continue
        if apply_homogeneity_correction(corr, floor, CLAIM_C_ALTERNATIVE) > alpha:
            continue                            # the derived refusal
        n_em += 1
        n_rej += int(apply_homogeneity_correction(
            corr, float(p), CLAIM_C_ALTERNATIVE) <= alpha)
    return (n_rej / n_em if n_em else float("nan")), n_em


class TestCalibrationIsRestored:
    """
    The measurement the whole build exists to make. Draw counts are stated in
    each assertion's tolerance rather than implied: these are ~6000-draw rates,
    so a nominal 0.05 is resolved to about +/- 0.006.
    """

    N = 8

    def _tables(self):
        return {len(c): SubsetPTable(self.N, len(c)) for _, c in SUBSETS}

    def test_the_worst_fitted_configuration_comes_back_to_nominal(self):
        """
        In-sample, so this checks the machinery rather than its
        generalisation: the curve was fitted on this family. What it rules out
        is an error of implementation -- a bin misread, a direction swapped, a
        correction applied to the wrong number.
        """
        tables = self._tables()
        rng = np.random.default_rng(31337)
        worst_raw = worst_corrected = 0.0
        # The high-bias uniform configurations are where the inflation lives.
        for shape, b in [c for c in _configs(M) if c == ("uniform", 0.3)
                         or c == ("uniform", 0.35) or c == ("khot:5", 0.4)]:
            res = simulate_config(self.N, M, SUBSETS, tables, shape, b,
                                  "none", 0.0, 15000, rng, ALPHA)
            emitted = res["emitted"]
            if emitted.sum() < 500:
                continue
            worst_raw = max(worst_raw,
                            float((res["p_greater"][emitted] <= ALPHA).mean()))
            rate, n_em = _corrected_rate(
                self.N, res["homogeneity"], emitted, res["p_greater"])
            if n_em >= 500:
                worst_corrected = max(worst_corrected, rate)

        assert worst_raw > 2 * ALPHA, (
            "fixture no longer reaches the inflated regime it is meant to test")
        assert worst_corrected <= ALPHA + 0.01

    def test_it_holds_on_a_dependence_family_the_curve_never_saw(self):
        """
        The arm that matters. `sign_homogeneity` is a scalar summary and a
        scalar cannot determine a distribution, so the open question is whether
        indexing the correction by it transfers to a different MECHANISM of
        dependence.

        The out-of-sample family is the duplicate-prompt mixture: with
        probability rho a prompt's sign row is a copy of a shared consensus row
        rather than its own draw. That is "some prompts are redundant", where
        the fitted family is "some metrics are architecture-wide" -- the same
        homogeneity reached by an unrelated route.
        """
        tables = self._tables()
        rng = np.random.default_rng(20260824)
        results = {}
        for rho in (0.4, 0.6, 0.8):
            consensus = rng.random((20000, 1, M)) < 0.5
            own = rng.random((20000, self.N, M)) < 0.5
            take = rng.random((20000, self.N, 1)) < rho
            table = np.where(take, np.broadcast_to(consensus, own.shape), own)

            hom, emitted, pg = _score(tables, table)
            raw = float((pg[emitted] <= ALPHA).mean())
            corrected, n_em = _corrected_rate(self.N, hom, emitted, pg)
            results[rho] = (raw, corrected, n_em)

        # Uncorrected, this family inflates the way the fitted one does.
        assert results[0.8][0] > 2 * ALPHA
        for rho, (raw, corrected, n_em) in results.items():
            assert n_em >= 500, f"rho={rho} emitted too little to measure"
            assert corrected <= ALPHA + 0.01, (
                f"rho={rho}: corrected rate {corrected:.4f} exceeds nominal on a "
                f"family the curve was not fitted to")
            assert corrected < raw + 1e-9


